"""Build any Verilog design for the real chip (classic_fabric_reram) and report what it used.

Uses the chip repo's own build recipe (user_designs/makefile.include: Yosys synth_fabulous,
nextpnr-generic --uarch fabulous, bit_gen.py) unchanged, from a work folder
chip_build/<name>/ outside the repo. The repo is only read.

Flow:
  1. copy the RTL into chip_build/<name>/rtl/ and write a Makefile that includes the repo recipe
  2. synth  -> read the top module's ports from the netlist
  3. pin budget: every port bit needs its own IOBUF site (36 on this fabric). If the design needs
     more, stop here with status "pin_budget_exceeded" (A1 must pick a narrower transfer protocol)
  4. write design.pcf (ports -> IOBUF sites, in site order), then pnr + bitstream + hex
  5. parse nextpnr's device utilisation, check the FASM is not empty and the bitstream has the
     size this fabric's frame layout implies
  6. V0 bitstream audit (chip/chip_bitstream.py): structure + decoded bits == FASM-required bits

The report (chip_build/<name>/flow_report.json) has a deterministic `failure` entry
(stage, cause, evidence) that the debug agent (A3) can consume.
"""
import json
import re
import shutil
import subprocess
import sys
import time
from pathlib import Path

from x2c.chip.chip_repo import PROJECT_ROOT, ChipRepo

FABRIC_CSV = "fabrics/classic_fabric_reram/classic_fabric_reram.csv"
DEFAULT_OUT = PROJECT_ROOT / "chip_build"
TOOLS = ("yosys", "nextpnr-generic", "python3", "make")

MAKEFILE = """# Generated by x2c (chip_flow.py). Builds {name} OUTSIDE the chip repo.
ifndef REPO
$(error REPO is not set)
endif
UD              = $(REPO)/user_designs
TOP             = {top}
RTL             = {rtl}
FABULOUS_ROOT   = $(UD)/fabrics/classic_fabric_reram/macro/sky130A/fabulous
PCF_CONSTRAINTS = $(CURDIR)/design.pcf
BIT_GEN         = $(UD)/scripts/bit_gen.py
BIT_TO_HEX      = $(UD)/scripts/bit_to_hex.py
include $(UD)/makefile.include
fix = $(subst ../../../../ip/,$(REPO)/ip/,$(1))
CELLS_MAP           := $(call fix,$(CELLS_MAP))
ARITH_MAP           := $(call fix,$(ARITH_MAP))
MULTIPLIER_MAP_PATH := $(call fix,$(MULTIPLIER_MAP_PATH))
EXTRA_PLIBS_PATH    := $(call fix,$(EXTRA_PLIBS_PATH))
EXTRA_MAPS_PATH     := $(call fix,$(EXTRA_MAPS_PATH))
EXTRA_MLIBMAPS_PATH := $(call fix,$(EXTRA_MLIBMAPS_PATH))
CLKBUF_MAP_PATH     := $(call fix,$(CLKBUF_MAP_PATH))
# x2c: corrected multiplier map (signed pieces); the repo's map is unsigned-only. See src/x2c/chip/techmap/MACC_8x8_20_map_signed.v
MULTIPLIER_MAP_PATH := -multiplier-map {multiplier_map} {multiplier_args}
"""

# The repo map (fabulous-tiles 0651993f) ignores A_SIGNED/B_SIGNED, so signed multiplies wider than 8 bits were wrong for
# negative operands. x2c's corrected copy replaces it, only after checking the repo still sets exactly this line.
REPO_MULTIPLIER_LINE = re.compile(r"^MULTIPLIER_MAP_PATH\s*=\s*-multiplier-map\s+(\S*/ip/fabulous-tiles/primitives/MACC_8x8_20/"
                                  r"yosys/techmap/MACC_8x8_20_map\.v)\s+(8 8 2 2 12)\s*$", re.M)
SIGNED_MAP = Path(__file__).resolve().parent / "techmap" / "MACC_8x8_20_map_signed.v"


def multiplier_override(repo):
    """(map path, args) for the generated Makefile. Raises if the repo's multiplier setting is not the one the corrected
    map was verified against (then a person must look again; nothing is overridden silently)."""
    text = repo.path("user_designs/makefile.include").read_text(errors="replace").replace("\r", "")
    m = REPO_MULTIPLIER_LINE.search(text)
    if not m:
        raise RuntimeError("the repo's MULTIPLIER_MAP_PATH line in user_designs/makefile.include changed; "
                           "re-check chip/techmap/MACC_8x8_20_map_signed.v against it before building")
    if not SIGNED_MAP.is_file():
        raise RuntimeError(f"missing {SIGNED_MAP}")
    return SIGNED_MAP.resolve().as_posix(), m.group(2)

_UTIL = re.compile(r"^Info:\s+(\w+):\s+(\d+)/\s*(\d+)\s+\d+%\s*$")


# ---------------------------------------------------------------- parsers (no tools needed)
def parse_utilisation(log_text):
    """nextpnr 'Device utilisation' block -> {type: {"used": u, "available": a}}."""
    out, inside = {}, False
    for line in log_text.splitlines():
        if line.startswith("Info: Device utilisation"):
            inside, out = True, {}
            continue
        if inside:
            m = _UTIL.match(line)
            if m:
                out[m.group(1)] = {"used": int(m.group(2)), "available": int(m.group(3))}
            elif out:
                inside = False
    return out


def ports_from_netlist(netlist, top):
    """Yosys JSON -> [(name, direction, width)] of the top module, in declaration order."""
    mod = netlist["modules"].get(top)
    if mod is None:
        raise ValueError(f"top module {top} not in netlist")
    return [(n, p["direction"], len(p["bits"])) for n, p in mod["ports"].items()]


def port_bits(ports):
    """[(name, direction, width)] -> pin names as nextpnr sees them (name, or name[i])."""
    names = []
    for n, _, w in ports:
        names += [n] if w == 1 else [f"{n}[{i}]" for i in range(w)]
    return names


def pin_plan(ports, io_sites):
    bits = port_bits(ports)
    return {"needed": len(bits), "available": len(io_sites), "fits": len(bits) <= len(io_sites),
            "by_port": {n: w for n, _, w in ports},
            "assignment": dict(zip(bits, io_sites)) if len(bits) <= len(io_sites) else {}}


def write_pcf(path, assignment):
    lines = ["# Generated by x2c (chip_flow.py): one IOBUF site per port bit"]
    lines += [f"set_io {name} {site}" for name, site in assignment.items()]
    Path(path).write_text("\n".join(lines) + "\n", encoding="ascii", newline="\n")


def frame_geometry(repo):
    """FrameBitsPerRow / MaxFramesPerCol from the fabric CSV (commented defaults count too)."""
    geo = {}
    for line in repo.read_text(FABRIC_CSV).splitlines():
        f = line.split(",")
        key = f[0].lstrip("#")
        if key in ("FrameBitsPerRow", "MaxFramesPerCol") and len(f) > 1 and f[1].strip().isdigit():
            geo[key] = int(f[1])
    if len(geo) != 2:
        raise ValueError(f"{FABRIC_CSV}: frame parameters not found: {geo}")
    return geo


def expected_bitstream_bytes(columns, rows, frames_per_col, frame_bits_per_row):
    """bit_gen.py layout: 20-byte header, per frame 4-byte header + rows * bits/8, 4-byte desync."""
    return 20 + columns * frames_per_col * (4 + rows * frame_bits_per_row // 8) + 4


def count_fasm_features(text):
    return sum(1 for line in text.splitlines() if line.strip() and not line.lstrip().startswith("#"))


def classify(stage, log_tail, extra=None):
    """Deterministic failure cause for A3. Unknown text -> 'unknown' (never guessed)."""
    t = log_tail.lower()
    rules = [
        ("pins", "pin_budget_exceeded", lambda: True),
        ("synth", "syntax_error", lambda: "syntax error" in t),
        ("synth", "unknown_module", lambda: "is not part of the design" in t),
        ("synth", "ff_type_unsupported", lambda: "cannot be legalized" in t),
        ("pnr", "over_capacity", lambda: "no bels remaining" in t or bool((extra or {}).get("over"))),
        ("pnr", "routing_failed", lambda: "failed to route" in t or "routing failed" in t),
        ("check", "unconstrained_io", lambda: bool((extra or {}).get("unconstrained"))),
        ("check", "empty_fasm", lambda: (extra or {}).get("fasm_features") == 0),
        ("check", "bitstream_size_mismatch", lambda: "size" in (extra or {}).get("why", "")),
        ("check", "bitstream_audit_failed", lambda: "audit" in (extra or {})),
        ("bitstream", "python_module_missing", lambda: "no module named" in t),
    ]
    for st, cause, test in rules:  # see RULE_EVIDENCE for which rules were seen on real logs
        if st == stage and test():
            return cause
    return "unknown"


# Which classify() rules have been checked against real tool output (2026-11-12, Yosys 0.70+368,
# nextpnr-0.11.1-89). The others match plausible text and may need adjusting when first seen.
RULE_EVIDENCE = {
    "pin_budget_exceeded": "real (x2c pre-check, bitslice_acc_parallel)",
    "syntax_error": "real Yosys log (bitslice_acc_bad)",
    "unknown_module": "real Yosys log (instantiated missing module)",
    "ff_type_unsupported": "real Yosys 0.66 log (old Yosys rejecting the repo's FF list)",
    "over_capacity": "real nextpnr log (20 multipliers on 18 MACC blocks)",
    "unconstrained_io": "real nextpnr behaviour: it places a missing pin itself and exits 0",
    "routing_failed": "NOT yet seen on a real log",
    "empty_fasm": "real (earlier FABulous demo finding: exit 0 with nothing placed)",
    "bitstream_size_mismatch": "NOT yet seen on a real log",
    "bitstream_audit_failed": "real bitstreams with planted bit flips (tests/test_chip_bitstream_audit.py)",
    "python_module_missing": "real make log: the Makefile's python3 was OSS CAD Suite's, without fasm (2026-11-13)",
}

_AUDIT_CACHE = {}


def _chip_audit(repo, bit_bytes, fasm_text, profile_json):
    """V0 audit (chip/chip_bitstream.py); the 41 MB spec is loaded once per process."""
    from x2c.chip.chip_bitstream import audit_chip_bitstream, chip_fabric_profile
    key = str(repo.root)
    if key not in _AUDIT_CACHE:
        _AUDIT_CACHE[key] = chip_fabric_profile(repo, chip_profile=profile_json)
    prof, spec = _AUDIT_CACHE[key]
    return audit_chip_bitstream(bit_bytes, fasm_text, profile=prof, spec=spec)


def constrained_pins(pnr_log):
    return re.findall(r"^Info: constrained '([^']+)' to bel", pnr_log, re.M)


# ---------------------------------------------------------------- the flow (needs Ubuntu tools)
def _run(cmd, cwd, env, log_path):
    t0 = time.time()
    r = subprocess.run(cmd, cwd=cwd, env=env, capture_output=True, text=True)
    Path(log_path).write_text(r.stdout + r.stderr)
    return r.returncode, r.stdout + r.stderr, round(time.time() - t0, 2)


MIN_YOSYS = (0, 70)          # the repo's synth options (-ff ...) need Yosys 0.70+; 0.66 fails with "Unknown option"


def tool_env(base=None):
    """PATH with the chip toolchain first: $CHIP_PY's folder (default: the Python running x2c, i.e. the project's .venv) and $CHIP_CAD/bin (default
    ~/tools/chip/oss-cad-suite/bin), when they exist. Same order as the chain's stage scripts: the repo Makefile runs
    bit_gen.py with the first python3 (needs fasm), and an older Yosys elsewhere on PATH must not win."""
    import os
    env = dict(base if base is not None else os.environ)
    home = Path(env.get("HOME", str(Path.home())))
    py = Path(env.get("CHIP_PY", sys.executable))          # the project environment has fasm (uv sync --all-extras)
    cad = Path(env.get("CHIP_CAD", home / "tools" / "chip" / "oss-cad-suite")) / "bin"
    first = [str(d) for d in (py.parent, cad) if d.is_dir()]
    env["PATH"] = os.pathsep.join(first + [env.get("PATH", "")])
    return env


def yosys_version(text):
    m = re.search(r"Yosys (\d+)\.(\d+)", text or "")
    return (int(m.group(1)), int(m.group(2))) if m else None


def run_flow(name, rtl_files, top, profile, repo=None, out_root=DEFAULT_OUT, env=None):
    repo = repo if isinstance(repo, ChipRepo) else ChipRepo(repo)
    env = tool_env(env)
    missing = [t for t in TOOLS if not shutil.which(t, path=env["PATH"])]
    if missing:
        raise RuntimeError(f"tools not found: {missing} (looked in $CHIP_PY's folder, $CHIP_CAD/bin and PATH)")
    ver = yosys_version(subprocess.run([shutil.which("yosys", path=env["PATH"]), "-V"], capture_output=True, text=True).stdout)
    if ver is None or ver < MIN_YOSYS:
        raise RuntimeError(f"Yosys {ver} found at {shutil.which('yosys', path=env['PATH'])}; the chip flow needs "
                           f"{MIN_YOSYS[0]}.{MIN_YOSYS[1]}+ (set CHIP_CAD to the chip OSS CAD Suite, default ~/tools/chip/oss-cad-suite)")
    if not re.fullmatch(r"[A-Za-z0-9_]+", name):
        raise ValueError("design name: letters, digits and _ only")
    work = Path(out_root) / name
    if work.exists():
        if not (work / "flow_report.json").is_file():
            raise ValueError(f"{work} exists and was not made by this runner; pick another --name")
        shutil.rmtree(work)  # only folders this runner made earlier are replaced
    (work / "rtl").mkdir(parents=True)
    # mark the folder as this runner's at once: if anything below crashes, the next run may still replace it
    (work / "flow_report.json").write_text(json.dumps({"design": name, "top": top, "status": "started"}) + "\n")
    rtl_local = []
    for f in rtl_files:
        dst = work / "rtl" / Path(f).name
        shutil.copyfile(f, dst)
        rtl_local.append("rtl/" + dst.name)
    mul_map, mul_args = multiplier_override(repo)
    (work / "Makefile").write_text(MAKEFILE.format(name=name, top=top, rtl=" ".join(rtl_local),
                                                   multiplier_map=mul_map, multiplier_args=mul_args),
                                   encoding="ascii", newline="\n")
    env["REPO"] = str(repo.root)
    env["PYTHONDONTWRITEBYTECODE"] = "1"

    before = repo.tree_fingerprint()
    report = {"design": name, "top": top, "rtl": [Path(f).name for f in rtl_files], "stages": {},
              "status": None, "failure": None,
              "multiplier_map": {"file": "src/x2c/chip/techmap/MACC_8x8_20_map_signed.v", "args": mul_args,
                                 "replaces": "ip/fabulous-tiles/primitives/MACC_8x8_20/yosys/techmap/MACC_8x8_20_map.v",
                                 "why": "the repo map is unsigned-only (signed multiplies wider than 8 bits were wrong)"}}

    def fail(stage, text, extra=None):
        tail = "\n".join(text.splitlines()[-25:])
        report["status"] = "failed"
        report["failure"] = {"stage": stage, "cause": classify(stage, tail, extra), "evidence": tail,
                             **({"details": extra} if extra else {})}

    rc, out, sec = _run(["make", "synth"], work, env, work / "synth.log")
    report["stages"]["synth"] = {"exit": rc, "seconds": sec}
    if rc != 0:
        fail("synth", out)
        return _finish(report, work, repo, before)

    ports = ports_from_netlist(json.loads((work / f"{top}.json").read_text()), top)
    plan = pin_plan(ports, profile["io"]["iobuf_site_list"])
    report["pins"] = {k: v for k, v in plan.items() if k != "assignment"}
    if not plan["fits"]:
        fail("pins", f"design needs {plan['needed']} I/O pins, fabric has {plan['available']} IOBUF sites",
             {"by_port": plan["by_port"]})
        return _finish(report, work, repo, before)
    write_pcf(work / "design.pcf", plan["assignment"])
    report["pins"]["assignment"] = plan["assignment"]

    for stage, target in (("pnr", "pnr"), ("bitstream", "bitstream"), ("hex", "hex")):
        rc, out, sec = _run(["make", target], work, env, work / f"{stage}.log")
        report["stages"][stage] = {"exit": rc, "seconds": sec}
        if stage == "pnr":
            report["utilisation"] = parse_utilisation(out)
            over = {k: v for k, v in report["utilisation"].items() if v["used"] > v["available"]}
            if rc != 0:
                fail(stage, out, {"over": over} if over else None)
                return _finish(report, work, repo, before)
            missing = sorted(set(plan["assignment"]) - set(constrained_pins(out)))
            if missing:
                fail("check", "nextpnr placed these pins without a constraint: " + ", ".join(missing),
                     {"unconstrained": missing})
                return _finish(report, work, repo, before)
        if rc != 0:
            fail(stage, out)
            return _finish(report, work, repo, before)

    fasm = work / f"{top}.fasm"
    n_feat = count_fasm_features(fasm.read_text()) if fasm.is_file() else 0
    bit = work / f"{top}.bit"
    size = bit.stat().st_size if bit.is_file() else 0
    geo = frame_geometry(repo)
    grid = profile["fabric"]["grid"]
    want = expected_bitstream_bytes(grid["columns"], grid["rows"], geo["MaxFramesPerCol"], geo["FrameBitsPerRow"])
    report["fasm_features"], report["bitstream_bytes"], report["bitstream_expected_bytes"] = n_feat, size, want
    if n_feat == 0:
        fail("check", "FASM has no features: the design was optimised away or nothing was placed",
             {"fasm_features": 0})
    elif size != want:
        fail("check", f"bitstream is {size} bytes, fabric layout implies {want}", {"why": "size"})
    else:
        audit = _chip_audit(repo, bit.read_bytes(), fasm.read_text(), profile)
        report["bitstream_audit"] = audit["summary"]
        (work / "bitstream_audit.json").write_text(json.dumps(audit, indent=2) + "\n")
        if audit["ok"]:
            report["status"] = "ok"
        else:
            fail("check", "V0 bitstream audit failed: " + json.dumps(audit["summary"]), {"audit": audit["summary"]})
    return _finish(report, work, repo, before)


def _finish(report, work, repo, before):
    report["chip_repo_read_only"] = before == repo.tree_fingerprint()
    if not report["chip_repo_read_only"]:
        report["status"] = "failed"
        report["failure"] = {"stage": "repo", "cause": "chip_repo_modified", "evidence": "fingerprint changed"}
    (work / "flow_report.json").write_text(json.dumps(report, indent=2) + "\n")
    return report
