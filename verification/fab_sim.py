"""
Fabric simulation of a wrapped operator: generate a self-checking testbench, and judge its log.

What runs (in Ubuntu, with FABulous' own `run_simulation`): FABulous' generated fabric RTL (`eFPGA_top`) is loaded with YOUR bitstream through the
configuration interface, exactly as the FABulous demo testbench does; then test vectors are driven onto the input pins and the output pins are
compared (1) with expected values computed by NumPy (independent of any Verilog) and (2) with the A2-verified RTL wrapper as a second reference.
ML analogy: the bitstream is the trained weights file; this loads it into the "model" (the fabric) and runs the test set against the labels.

Rules: only a log with ONE `FAB_SIM RESULT: PASS` line, a vector count equal to the table in the testbench, and zero mismatches is a pass. A log
without a result line (compile error, simulator crash, "completed successfully" with nothing compared) is inconclusive, never a pass.
Evidence level: RTL simulation of the FABulous fabric model with the generated bitstream loaded (Icarus) vs NumPy golden
(NOT gate-level, NOT timing, NOT silicon).
"""
import re

from verification.fab_wrap import IO_WIDTH, split_halves, top_name, wrapper_layout
from verification.rtl_check import OPS, vectors_for

EVIDENCE_LEVEL = ("rtl_simulation_of_fabulous_fabric_with_generated_bitstream_vs_numpy_golden "
                  "(NOT gate-level, NOT timing, NOT silicon)")
RESULT = re.compile(r"^FAB_SIM RESULT: (PASS|FAIL) vectors=(\d+) numpy_mismatches=(\d+) rtl_mismatches=(\d+)\s*$", re.M)
MISMATCH = re.compile(r"^FAB_SIM MISMATCH .*$", re.M)


def sim_vectors(op):
    """[(io_in word, expected result bits)] with expected values from the NumPy golden model.
    For a two-step load: [(low-half word, expected, high-half word)]."""
    lay = wrapper_layout(op)
    vec = vectors_for(op)
    gold = OPS[op]["golden"](vec)
    n = len(next(iter(vec.values())))
    mask = (1 << lay["out_width"]) - 1
    out = []
    if lay["mode"] == "two_step":
        for i in range(n):
            lo, hi = split_halves(vec[lay["in_name"]][i], lay)
            out.append((lo, int(gold[i]) & mask, hi))
        return out
    for i in range(n):
        word = 0
        for name, (lo, w) in lay["inputs"].items():
            word |= (int(vec[name][i]) & ((1 << w) - 1)) << lo
        out.append((word, int(gold[i]) & mask))
    return out


def make_fab_testbench(op):
    lay = wrapper_layout(op)
    top, ow = top_name(op), lay["out_width"]
    vecs = sim_vectors(op)
    two = lay["mode"] == "two_step"
    table = "\n".join(f"        vec_in[{i}] = {IO_WIDTH}'h{v[0]:07X}; vec_exp[{i}] = {ow}'h{v[1]:0{(ow + 3) // 4}X};"
                      + (f" vec_hi[{i}] = {IO_WIDTH}'h{v[2]:07X};" if two else "") for i, v in enumerate(vecs))
    hi_decl = f"\n    reg [{IO_WIDTH - 1}:0] vec_hi  [0:NVEC-1];       // two-step load: the second word (high half, select pin = 1)" if two else ""
    drive = ("""            @(negedge CLK);
            O_top = vec_in[i];                  // tick 1: the low half (select pin = 0)
            @(posedge CLK);
            @(negedge CLK);
            O_top = vec_hi[i];                  // tick 2: the high half (select pin = 1); tick 3 registers the result
            repeat (3) @(posedge CLK);""" if two else """            @(negedge CLK);
            O_top = vec_in[i];
            repeat (3) @(posedge CLK);""")
    return f"""`timescale 1ps / 1ps
`default_nettype none

// Self-checking testbench for {top}, generated by verification/fab_sim.py (structure follows FABulous' own sequential_16bit_en_tb.v).
module {top}_tb ();
    wire [{IO_WIDTH - 1}:0] I_top;
    wire [{IO_WIDTH - 1}:0] T_top;
    reg  [{IO_WIDTH - 1}:0] O_top = 0;
    wire [55:0] A_cfg, B_cfg;

    reg         CLK               = 1'b0;
    reg         resetn            = 1'b1;
    reg         self_write_strobe = 1'b0;
    reg  [31:0] self_write_data   = 32'b0;
    reg         rx                = 1'b1;
    wire        com_active;
    wire        receive_led;
    reg         s_clk             = 1'b0;
    reg         s_data            = 1'b0;

    // the real fabric, to be configured with the bitstream
    eFPGA_top top_i (
        .I_top          (I_top),
        .T_top          (T_top),
        .O_top          (O_top),
        .A_config_C     (A_cfg),
        .B_config_C     (B_cfg),
        .CLK            (CLK),
        .resetn         (resetn),
        .SelfWriteStrobe(self_write_strobe),
        .SelfWriteData  (self_write_data),
        .Rx             (rx),
        .ComActive      (com_active),
        .ReceiveLED     (receive_led),
        .s_clk          (s_clk),
        .s_data         (s_data)
    );

    // second reference: the A2-verified RTL wrapper
    wire [{IO_WIDTH - 1}:0] I_top_gold, oeb_gold, T_top_gold;
    {top} dut_i (.clk(CLK), .io_in(O_top), .io_out(I_top_gold), .io_oeb(oeb_gold));
    assign T_top_gold = ~oeb_gold;

    localparam integer MAX_BITBYTES = 16384;
    localparam integer NVEC = {len(vecs)};
    reg [7:0]  bitstream [0:MAX_BITBYTES-1];
    reg [{IO_WIDTH - 1}:0] vec_in  [0:NVEC-1];
    reg [{ow - 1}:0]  vec_exp [0:NVEC-1];{hi_decl}

    always #500000 CLK = (CLK === 1'b0);

    integer i, checked, numpy_mismatches, rtl_mismatches;
    reg [2047:0] bitstream_hex_arg;
    reg [2047:0] output_waveform_arg;

    initial begin
{table}
    end

    initial begin
        checked = 0; numpy_mismatches = 0; rtl_mismatches = 0;
        if ($value$plusargs("output_waveform=%s", output_waveform_arg)) begin
            $dumpfile(output_waveform_arg);
            $dumpvars(0, {top}_tb);
        end
        if ($value$plusargs("bitstream_hex=%s", bitstream_hex_arg)) begin
            $readmemh(bitstream_hex_arg, bitstream);
            $display("Read bitstream hex from %0s", bitstream_hex_arg);
        end else begin
            $display("FAB_SIM RESULT: FAIL vectors=0 numpy_mismatches=0 rtl_mismatches=0");
            $display("FAB_SIM no bitstream given (+bitstream_hex=...)");
            $finish;
        end

        #100;
        resetn = 1'b0;
        #10000;
        resetn = 1'b1;
        #10000;
        repeat (20) @(posedge CLK);
        #2500;
        // upload the bitstream word by word through the self-write port
        for (i = 0; i < MAX_BITBYTES; i = i + 4) begin
            self_write_data <= {{bitstream[i], bitstream[i+1], bitstream[i+2], bitstream[i+3]}};
            repeat (2) @(posedge CLK);
            self_write_strobe <= 1'b1;
            @(posedge CLK);
            self_write_strobe <= 1'b0;
            repeat (2) @(posedge CLK);
        end
        repeat (100) @(posedge CLK);

        // drive every vector, wait for the registered result, compare
        for (i = 0; i < NVEC; i = i + 1) begin
{drive}
            @(negedge CLK);
            checked = checked + 1;
            if (I_top[{lay['out_lsb'] + ow - 1}:{lay['out_lsb']}] !== vec_exp[i]) begin
                numpy_mismatches = numpy_mismatches + 1;
                if (numpy_mismatches <= 5)
                    $display("FAB_SIM MISMATCH vector %0d: io_in=0x%07X expected=0x%0X fabric=0x%0X",
                             i, vec_in[i], vec_exp[i], I_top[{lay['out_lsb'] + ow - 1}:{lay['out_lsb']}]);
            end
            if (I_top !== I_top_gold || T_top !== T_top_gold) rtl_mismatches = rtl_mismatches + 1;
        end

        if (numpy_mismatches == 0 && rtl_mismatches == 0 && checked == NVEC)
            $display("FAB_SIM RESULT: PASS vectors=%0d numpy_mismatches=%0d rtl_mismatches=%0d", checked, numpy_mismatches, rtl_mismatches);
        else
            $display("FAB_SIM RESULT: FAIL vectors=%0d numpy_mismatches=%0d rtl_mismatches=%0d", checked, numpy_mismatches, rtl_mismatches);
        $finish;
    end
endmodule
`resetall
"""


def tb_vector_count(tb_text):
    return len(re.findall(r"vec_in\[\d+\]\s*=", tb_text))


def parse_sim_log(text, expected_vectors=None):
    """Verdict on a simulation log: {status: pass|fail|inconclusive, ...}. `expected_vectors` is the size of the table in the testbench."""
    found = RESULT.findall(text or "")
    mism = MISMATCH.findall(text or "")[:5]
    if len(found) != 1:
        errs = [l.strip() for l in (text or "").splitlines() if re.search(r"\berror\b|Fatal|\bunknown module\b", l, re.I)][:3]
        why = "no FAB_SIM RESULT line: the simulation did not finish or did not compare anything" if not found else "more than one FAB_SIM RESULT line"
        return {"status": "inconclusive", "reason": why, "tool_errors": errs}
    verdict, n, nm, rm = found[0][0], int(found[0][1]), int(found[0][2]), int(found[0][3])
    base = {"vectors": n, "numpy_mismatches": nm, "rtl_mismatches": rm, "mismatch_lines": mism, "evidence_level": EVIDENCE_LEVEL}
    if verdict == "FAIL" or nm or rm:
        return {"status": "fail", "reason": f"{nm} numpy mismatch(es), {rm} rtl mismatch(es) in {n} vectors", **base}
    if n == 0 or (expected_vectors is not None and n != expected_vectors):
        return {"status": "inconclusive", "reason": f"{n} vectors compared, expected {expected_vectors}", **base}
    return {"status": "pass", "reason": f"{n} vectors match the NumPy golden model and the RTL reference", **base}
